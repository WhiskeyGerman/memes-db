def upgrade() -> None:
    """Создать таблицы и уникальные ограничения начального релиза."""
    for statement in SCHEMA_SQL:
        op.execute(statement)


def downgrade() -> None:
    """Откатить принадлежащие Catalog объекты схемы."""
    for table in TABLES:
        op.drop_table(table)
